"""Regenerates src/terrain/land_tiles.inc: which 1 x 1 degree cells have a Copernicus DEM tile (= land).

Input: the tile lists of the two AWS buckets (copernicus-dem-30m/tileList.txt, copernicus-dem-90m/tileList.txt),
or any text with one tile name per line like N34W119 or Copernicus_DSM_COG_10_N34_00_W119_00_DEM. Output: a bit per
cell, row = latitude + 90 (south to north), column = longitude + 180, 360 bits a row, least significant bit first.

    python tools/terrain/make_land.py tileList30.txt tileList90.txt > src/terrain/land_tiles.inc
"""
import re
import sys

bits = bytearray(180 * 360 // 8)
n = 0
for path in sys.argv[1:]:
    for line in open(path, encoding="ascii", errors="ignore"):
        m = re.search(r"([NS])(\d\d)(?:_00)?_?([EW])(\d\d\d)", line)
        if not m:
            continue
        lat = int(m[2]) * (1 if m[1] == "N" else -1)
        lon = int(m[4]) * (1 if m[3] == "E" else -1)
        i = (lat + 90) * 360 + (lon + 180)
        if not bits[i >> 3] & (1 << (i & 7)):
            n += 1
        bits[i >> 3] |= 1 << (i & 7)
print(f"// Generated by tools/terrain/make_land.py from the Copernicus DEM tile lists: {n} land cells.")
for k in range(0, len(bits), 24):
    print("".join(f"0x{b:02x}," for b in bits[k:k + 24]))
